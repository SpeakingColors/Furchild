#!/usr/bin/env python3
"""Generates src/editor/Presets.h from the mockup FACTORY list (16 presets)."""
import re,json
src=open('/home/claude/furchild-mockup/Furchild-v1.1.html').read()
DEF=dict(inA=0,inB=0,thA=2,thB=2,tcA=2,tcB=2,mode=0,link=1,out=2,mix=100,hp=0,bypass=0,levelMatch=0)
block=src[src.index('const FACTORY=['):src.index('];',src.index('const FACTORY=['))]
rows=re.findall(r"F\('([^']+)','([^']+)',\[([^\]]*)\],\{([^}]*)\}\)",block)
out=['// Generated by tools/presets.py from the mockup. Do not edit by hand.','#pragma once','namespace fcp {','struct Preset { const char* name; const char* type; const char* tags; float v[13]; };','inline constexpr Preset kFactory[] = {']
keys=list(DEF)
for name,typ,tags,body in rows:
    p=dict(DEF)
    for k,v in re.findall(r"(\w+):(-?[\d.]+)",body):
        v=float(v)
        if k in('in','th','tc'): p[k+'A']=v;p[k+'B']=v
        else: p[k]=v
    tg=','.join(t.strip().strip("'") for t in tags.split(','))
    out.append('    {"%s","%s","%s",{%s}},'%(name,typ,tg,','.join((('%g'%p[k])+('' if '.' in '%g'%p[k] else '.0')+'f') for k in keys)))
out+=['};','inline constexpr int kNumFactory = (int)(sizeof(kFactory)/sizeof(kFactory[0]));','}']
open('src/editor/Presets.h','w').write('\n'.join(out)+'\n');print(len(rows),'presets')
