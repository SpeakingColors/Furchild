#!/usr/bin/env python3
"""Generate src/editor/Layout.h from docs/mockup/layout.json (made by tools/dump_layout.py from the approved
mockup). Every position, size, label and tooltip of the native window comes from here. Run from the repo root.
The mockup page has a preview rig under the knobs ("not part of the plugin"). The real window leaves it out:
everything below the knobs moves up by the rig height."""
import json
d = json.load(open('docs/mockup/layout.json'))
RIG = d['rig']['r'][3]
H = int(640 - RIG)

def q(s):
    out = ''
    for ch in s:
        if ch == '\\': out += '\\\\'
        elif ch == '"': out += '\\"'
        elif ord(ch) < 128: out += ch
        else: out += ''.join('\\%03o' % b for b in ch.encode('utf-8'))
    return '"' + out + '"'
def f(v):
    t = '%g' % v
    if 'e' in t: t = '%.4f' % v
    return t + ('' if '.' in t else '.0') + 'f'
def rc(r): return '{ ' + ', '.join(f(v) for v in r) + ' }'
def up(r): return [r[0], r[1] - RIG, r[2], r[3]]   # element below the rig moves up

o = []
o.append('// GENERATED by tools/gen_layout.py from docs/mockup/layout.json. Do not edit by hand.')
o.append('#pragma once')
o.append('namespace layout {')
o.append('struct Rc { float x, y, w, h; };')
o.append('struct Txt { const char* s; Rc r; float size; float spacing; };')
o.append('struct KnobCell { Rc label; Rc knob; Rc value; Rc ends[2]; bool hasEnds; float labelSize; float labelSpacing; };')
o.append('struct Row { const char* s; bool bold; float x, y, w, h; };')
o.append('struct Led { float cx, cy; int value; };')
o.append('constexpr int W = 1200, H = %d;' % H)
body = list(d['body']['r']); body[3] -= RIG
cl = list(d['cheekL']['r']); cl[3] -= RIG
cr = list(d['cheekR']['r']); cr[3] -= RIG
mt = list(d['meters']['r']); mt[3] -= RIG
for k, r in [('cheekL', cl), ('cheekR', cr), ('hdr', d['hdr']['r']), ('body', body), ('disp', d['disp']['r']), ('knobs', d['knobs']['r']),
             ('meters', mt), ('foot', up(d['foot']['r'])), ('logo', d['logo']['r']), ('grpA', d['grpA']['r']), ('grpB', d['grpB']['r']),
             ('midCol', d['mid']['r'])]:
    o.append('constexpr Rc %s = %s;' % (k, rc(r)))
o.append('constexpr float brandSize = %s;' % f(d['name']['fs']))
for k in ['name', 's87', 'ghA', 'ghB', 'hpCap', 'footL']:
    t = d[k]
    r = up(t['r']) if k == 'footL' else t['r']
    o.append('constexpr Txt %s = { %s, %s, %s, %s };' % (k, q(t['t']), rc(r), f(t['fs']), f(t['ls'])))
o.append('constexpr Rc winsz = %s;' % rc(up(d['winsz']['r'])))
# buttons and controls: rect plus tip
def ctl(k, shift=False):
    t = d[k]; r = up(t['r']) if shift else t['r']
    return '{ %s, %s }' % (rc(r), q(t['tip']))
o.append('struct Ctl { Rc r; const char* tip; };')
for k in ['pPrev', 'pName', 'pNext', 'pSave', 'bBypass', 'bGuide', 'bSettings', 'bAbout', 'mLR', 'mLV', 'bLink', 'bLevel', 'mtR', 'mtL', 'selHP', 'cvDialA', 'cvDialB', 'cvCurve', 'cvHist', 'cvTubes', 'cvIn', 'cvOut']:
    o.append('constexpr Ctl %s = %s;' % (k, ctl(k)))
for k in ['pkIn', 'pkOut']:
    o.append('constexpr Ctl %s = %s;' % (k, '{ %s, %s }' % (rc(d[k]['r']), q(d[k]['tip']))))
for k in ['capA', 'capB', 'dsA', 'dtA', 'dsB', 'dtB', 'hsA', 'hsB']:
    o.append('constexpr Rc %s = %s;' % (k, rc(d[k]['r'])))
o.append('constexpr Txt dispCaps[2] = { %s, %s };' % tuple('{ %s, %s, %s, %s }' % (q(c['cap']['t']), rc(c['cap']['r']), f(c['cap']['fs']), f(c['cap']['ls'])) for c in d['dcells'][2:]))
o.append('constexpr Rc dispSubs[4] = { %s };' % ', '.join(rc(s['r']) for c in d['dcells'][2:] for s in c['sub']))
o.append('constexpr const char* dispSubText[4] = { %s };' % ', '.join(q(s['t']) for c in d['dcells'][2:] for s in c['sub']))
o.append('constexpr Txt meterCaps[2] = { %s };' % ', '.join('{ %s, %s, %s, %s }' % (q(m['t']), rc(m['r']), f(m['fs']), f(m['ls'])) for m in d['mcap']))
o.append('constexpr const char* hpItems[4] = { %s };' % ', '.join(q(s) for s in d['sel']))
for i, ch in enumerate('AB'):
    b = d['ladderBox'][i]
    o.append('constexpr Rc ladderBox%s = %s;' % (ch, rc(b['r'])))
    o.append('constexpr Led ladder%s[12] = { %s };' % (ch, ', '.join('{ %s, %s, %d }' % (f(l['led'][0] + l['led'][2] / 2), f(l['led'][1] + l['led'][3] / 2), int(l['n']['t'])) for l in d['ladders'][i])))
    o.append('constexpr Rc ladderNum%s[12] = { %s };' % (ch, ', '.join(rc(l['n']['r']) for l in d['ladders'][i])))
o.append('constexpr const char* ladderTip = %s;' % q(d['ladderBox'][0]['tip']))
names = ['inA', 'thA', 'tcA', 'out', 'mix', 'inB', 'thB', 'tcB']
o.append('// knob cells in the order inA, thA, tcA, out, mix, inB, thB, tcB')
cells = []
for c in d['cells']:
    ends = c['ends'] if c['ends'] else [{'r': [0, 0, 0, 0]}, {'r': [0, 0, 0, 0]}]
    cells.append('{ %s, %s, %s, { %s, %s }, %s, %s, %s }' % (rc(c['lab']['r']), rc(c['knob']['r']), rc(c['kval']['r']), rc(ends[0]['r']), rc(ends[1]['r']),
                                                           'true' if c['ends'] else 'false', f(c['lab']['fs']), f(c['lab']['ls'])))
o.append('constexpr KnobCell cells[8] = {\n    ' + ',\n    '.join(cells) + ' };')
o.append('constexpr const char* cellNames[8] = { %s };' % ', '.join(q(n) for n in names))
o.append('constexpr const char* cellLabels[8] = { %s };' % ', '.join(q(c['lab']['t']) for c in d['cells']))
o.append('constexpr const char* cellTips[8] = {\n    ' + ',\n    '.join(q(c['knob']['tip']) for c in d['cells']) + ' };')
o.append('constexpr float cellKnobSize[8] = { %s };' % ', '.join(f(c['knob']['r'][2] - 0) for c in d['cells']))
# value rows (y of each text line) per cell, default state
o.append('constexpr float valRowY[8][3] = { %s };' % ', '.join('{ ' + ', '.join(f(v) for v in ([r['y'] for r in c['rows'] if True] + [0, 0, 0])[:3]) + ' }' for c in d['cells']))
rowsY = []
for c in d['cells']:
    ys = []
    for r in c['rows']:
        if r['y'] not in ys: ys.append(r['y'])
    rowsY.append(ys + [0] * (3 - len(ys)))
o[-1] = 'constexpr float valRowY[8][3] = { %s };' % ', '.join('{ ' + ', '.join(f(v) for v in ys[:3]) + ' }' for ys in rowsY)
o.append('constexpr int valRowCount[8] = { %s };' % ', '.join(str(len([y for y in ys if y])) for ys in rowsY))
o.append('constexpr float valRowH = %s;' % f(d['cells'][0]['rows'][0]['h']))
o.append('} // namespace layout')
open('src/editor/Layout.h', 'w').write('\n'.join(o) + '\n')
print('ok H =', H)
